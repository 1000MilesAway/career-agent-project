import type { ReactNode } from 'react'
import { Link } from 'react-router-dom'
import { LoginHome } from './LoginPage'
import './legal.css'

export type LegalDoc = 'terms' | 'privacy'

export const LEGAL_TITLES: Record<LegalDoc, string> = {
  terms: 'Пользовательское соглашение',
  privacy: 'Политика конфиденциальности',
}

/** The edition date; change it with the text. */
const EDITION = '02.10.2026'
/** The service as the templates name it, in place of their «ваш сайт/ тг бот». */
const SERVICE = 'career-helper.site'

/** Standalone, for a visitor without an account. */
export function LegalScreen({ doc }: { doc: LegalDoc }) {
  return (
    <main className="legal-screen">
      <LoginHome />
      <LegalPage doc={doc} />
    </main>
  )
}

export function LegalPage({ doc }: { doc: LegalDoc }) {
  return (
    <article className="page legal">
      <h1 className="page__title">{LEGAL_TITLES[doc]}</h1>
      <p className="legal__edition">{EDITION}</p>
      {doc === 'terms' ? <Terms /> : <Privacy />}
      <p className="legal__other">
        {doc === 'terms' ? (
          <Link to="/privacy">{LEGAL_TITLES.privacy}</Link>
        ) : (
          <Link to="/terms">{LEGAL_TITLES.terms}</Link>
        )}
      </p>
    </article>
  )
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="legal__section">
      <h2>{title}</h2>
      {children}
    </section>
  )
}

