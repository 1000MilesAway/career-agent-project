/** The texts of the legal documents.
 *
 * Three documents, not one, on purpose: since 2025-09-01 152-FZ wants consent
 * to processing as a document of its own, not a paragraph inside the terms or
 * the policy. The lists of data and recipients repeat between the consent and
 * the policy for the same reason — each has to stand on its own.
 *
 * Everything here must stay true of the code: a recipient added to the
 * pipeline (another model provider, an analytics script) is a change of these
 * texts and of EDITION, or the policy starts lying.
 */

import type { ReactNode } from 'react'
import { EDITION, OPERATOR, SITE } from './operator'

export type DocId = 'privacy' | 'consent' | 'terms'

function Missing() {
  return <span className="legal__missing">уточняется</span>
}

function OperatorName() {
  return OPERATOR.name ? <>{OPERATOR.name}</> : <Missing />
}

function OperatorEmail() {
  return OPERATOR.email ? (
    <a href={`mailto:${OPERATOR.email}`}>{OPERATOR.email}</a>
  ) : (
    <Missing />
  )
}

function Requisites() {
  return (
    <ul>
      <li>
        Оператор: <OperatorName />
      </li>
      <li>ИНН: {OPERATOR.inn ?? <Missing />}</li>
      <li>
        Почта для обращений: <OperatorEmail />
      </li>
      <li>
        Сайт: <a href={SITE}>{SITE.replace('https://', '')}</a>
      </li>
    </ul>
  )
}

function Edition() {
  return <p className="legal__edition">Редакция от {EDITION}</p>
}

function DocLink({ to, children }: { to: DocId; children: ReactNode }) {
  return <a href={`#/legal/${to}`}>{children}</a>
}

